#!/usr/bin/env python3
"""Validate an application-produced STRICT_LIVE audit report without making API calls.

This verifies that the supplied runtime audit satisfies the declared evidence
contract. It does not create or simulate provider execution, and it does not
replace an audit generated by the deployed application.
"""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent
DEFAULT_REPORT = ROOT / "evidence" / "HOTFIX164.26_RUNTIME_BRIDGE_AUDIT.json"
REPORT_SCHEMA = "hotfix164.23-explicit-target-read-only-forensics/v1"
EXPECTED_ARTIFACTS = {
    "AUTHORITATIVE_METRICS", "BRIDGE_AUDIT", "CASCADE_SUMMARIES", "EXECUTED_MODELS",
    "FINAL_RESULT", "REQUEST_ID", "ROUND_ID", "SEAT_RESULTS", "SESSION_ID", "USER_MESSAGE",
}


def validate_report(report: dict[str, Any]) -> list[str]:
    errors: list[str] = []
    def need(condition: bool, code: str) -> None:
        if not condition:
            errors.append(code)

    need(report.get("schema") == REPORT_SCHEMA, "REPORT_SCHEMA_MISMATCH")
    need(report.get("status") == "PASS", "REPORT_STATUS_NOT_PASS")
    need(report.get("blockers") == [], "REPORT_HAS_BLOCKERS")
    need(report.get("mode") == "READ_ONLY_EXPLICIT_TARGETS", "REPORT_MODE_MISMATCH")
    for key in ("read_only", "read_only_live_state_unchanged", "live_state_unchanged",
                "canonical_counter_consistent", "canonical_identity_chain_valid",
                "canonical_history_hash_stable_during_audit", "historical_records_preserved"):
        need(report.get(key) is True, f"{key.upper()}_NOT_TRUE")
    need(report.get("read_only_side_effects") == "NONE_OBSERVED", "READ_ONLY_SIDE_EFFECTS_OBSERVED")
    need(report.get("read_side_effects") == "NONE_OBSERVED", "READ_SIDE_EFFECTS_OBSERVED")
    need(report.get("target_selection_status") == "EXPLICIT_TARGETS_SELECTED", "TARGETS_NOT_EXPLICIT")
    need(report.get("target_request_count") == 2, "TARGET_REQUEST_COUNT_NOT_TWO")
    selected_ids = report.get("target_request_ids")
    need(isinstance(selected_ids, list) and len(selected_ids) == 2
         and all(isinstance(rid, str) and rid.strip() for rid in selected_ids)
         and len(set(selected_ids)) == 2, "TARGET_REQUEST_IDS_INVALID_OR_DUPLICATE")
    need(report.get("canonical_counts") == {
        "canonical_message_count": 2,
        "canonical_request_count": 2,
        "canonical_round_count": 2,
    }, "CANONICAL_COUNTS_MISMATCH")
    need(report.get("canonical_counter_status") == "PASS", "CANONICAL_COUNTER_NOT_PASS")
    need(report.get("canonical_vs_persisted_request_counter_status") == "PASS", "PERSISTED_COUNTER_NOT_PASS")
    need(report.get("duplicate_canonical_request_ids") == [], "DUPLICATE_CANONICAL_REQUEST_IDS")
    need(report.get("projection_only_request_ids") == [], "PROJECTION_ONLY_REQUESTS_PRESENT")
    need(report.get("new_requests") == report.get("new_rounds") == report.get("new_bridges") == 0,
         "AUDIT_CREATED_NEW_RUNTIME_STATE")
    need(report.get("provider_execution") == 0 and report.get("cascade_execution") == 0,
         "READ_ONLY_AUDIT_EXECUTED_PROVIDER_WORK")
    event_count = report.get("runtime_execution_event_count")
    started_count = report.get("execution_started_count")
    request_rows = report.get("requests")
    need(isinstance(event_count, int) and event_count > 0, "NO_PERSISTED_RUNTIME_EXECUTION_EVENTS")
    need(isinstance(started_count, int) and started_count == event_count, "RUNTIME_EVENT_COUNT_MISMATCH")
    need(isinstance(request_rows, list) and len(request_rows) == 2, "REQUEST_ROWS_NOT_TWO")

    if isinstance(request_rows, list) and len(request_rows) == 2:
        need(isinstance(selected_ids, list) and [row.get("request_id") for row in request_rows] == selected_ids,
             "REQUEST_ROWS_ID_MISMATCH")
        need(sum(row.get("execution_started_count", 0) for row in request_rows) == event_count,
             "PER_REQUEST_EXECUTION_COUNT_MISMATCH")
        for i, row in enumerate(request_rows, start=1):
            need(row.get("status") == "PASS", f"REQUEST_{i}_NOT_PASS")
            need(row.get("bridge_requested") is True, f"REQUEST_{i}_BRIDGE_NOT_REQUESTED")
            need(row.get("bridge_contract") == "STRICT_LIVE", f"REQUEST_{i}_NOT_STRICT_LIVE")
            for key in ("canonical_request_present", "actual_model_attestation_present",
                        "authoritative_metrics_present", "cascade_summary_present",
                        "direct_request_projection_present", "synthesis_record_present"):
                need(row.get(key) is True, f"REQUEST_{i}_{key.upper()}_MISSING")
            for key in ("canonical_round_binding_status", "execution_identity_status",
                        "message_identity_status", "request_execution_status",
                        "result_request_identity_status", "strict_live_bridge_status"):
                need(row.get(key) == "PASS", f"REQUEST_{i}_{key.upper()}_NOT_PASS")
            need(row.get("missing_required_artifacts") == [], f"REQUEST_{i}_MISSING_REQUIRED_ARTIFACTS")
            artifacts = row.get("required_artifacts")
            need(isinstance(artifacts, dict) and set(artifacts) == EXPECTED_ARTIFACTS
                 and all(v == "PASS" for v in artifacts.values()), f"REQUEST_{i}_ARTIFACTS_NOT_COMPLETE")

    strict = report.get("strict_live_bridge_proof")
    need(isinstance(strict, dict), "STRICT_LIVE_PROOF_MISSING")
    if isinstance(strict, dict):
        need(strict.get("schema") == "strict-live-bridge-proof-diagnostics/v1", "STRICT_LIVE_SCHEMA_MISMATCH")
        need(strict.get("authoritative_source") == "APPLICATION_OWNED_BRIDGE_RUNTIME_EVIDENCE_STORE",
             "STRICT_LIVE_SOURCE_NOT_APPLICATION_OWNED")
        need(strict.get("status") == "PASS" and strict.get("request_count") == 2, "STRICT_LIVE_PROOF_NOT_PASS")
        for key in ("raw_bridge_id_exported", "raw_bridge_value_exported", "raw_prompt_or_http_body_exported"):
            need(strict.get(key) is False, f"SENSITIVE_EXPORT_FLAG_{key.upper()}_TRUE")
        records = strict.get("records")
        need(isinstance(records, list) and len(records) == 2, "STRICT_LIVE_RECORD_COUNT_NOT_TWO")
        if isinstance(records, list) and len(records) == 2:
            need(isinstance(selected_ids, list) and [row.get("request_id") for row in records] == selected_ids,
                 "STRICT_LIVE_RECORD_IDS_MISMATCH")
            for i, row in enumerate(records, start=1):
                need(row.get("status") == "PASS" and row.get("evidence_record_present") is True,
                     f"STRICT_LIVE_RECORD_{i}_NOT_PASS")
                need(row.get("request_identity_status") == "PASS"
                     and row.get("canonical_round_binding_status") == "PASS",
                     f"STRICT_LIVE_RECORD_{i}_IDENTITY_NOT_PASS")
                need(row.get("failure_reasons") == [] and row.get("missing_evidence") == [],
                     f"STRICT_LIVE_RECORD_{i}_INCOMPLETE")

    target_rows = report.get("target_requests")
    need(isinstance(target_rows, list) and len(target_rows) == 2, "TARGET_ROWS_NOT_TWO")
    if isinstance(target_rows, list) and len(target_rows) == 2:
        need(isinstance(selected_ids, list) and [row.get("request_id") for row in target_rows] == selected_ids,
             "TARGET_ROWS_ID_MISMATCH")
        bridge_hashes: list[str] = []
        for i, row in enumerate(target_rows, start=1):
            need(row.get("status") == "PASS" and row.get("bridge_proof_status") == "PASS",
                 f"TARGET_{i}_BRIDGE_PROOF_NOT_PASS")
            for key in ("bridge_projection_binding_status", "bridge_request_round_binding_status",
                        "canonical_request_status", "canonical_round_binding_status",
                        "message_request_binding_status", "required_request_artifacts_status"):
                need(row.get(key) == "PASS", f"TARGET_{i}_{key.upper()}_NOT_PASS")
            need(row.get("bridge_projection_record_count_for_request") == 1
                 and row.get("bridge_runtime_evidence_record_count_for_request") == 1,
                 f"TARGET_{i}_EVIDENCE_RECORD_COUNT_MISMATCH")
            need(row.get("failure_reasons") == [] and row.get("missing_evidence") == [],
                 f"TARGET_{i}_EVIDENCE_INCOMPLETE")
            need(str(row.get("canonical_round_ordinal")) == str(i), f"TARGET_{i}_ROUND_ORDINAL_MISMATCH")
            rid = row.get("request_id", "")
            need(isinstance(row.get("canonical_round_id"), str)
                 and rid in row["canonical_round_id"], f"TARGET_{i}_CANONICAL_ROUND_BINDING_MISMATCH")
            h = row.get("bridge_id_hash")
            need(isinstance(h, str) and re.fullmatch(r"[0-9a-f]{64}", h) is not None,
                 f"TARGET_{i}_BRIDGE_HASH_INVALID")
            if isinstance(h, str):
                bridge_hashes.append(h)
        need(len(bridge_hashes) == 2 and len(set(bridge_hashes)) == 2,
             "BRIDGE_HASHES_NOT_DISTINCT")
    need(report.get("target_bridge_independence_status") == "PASS", "TARGET_BRIDGE_INDEPENDENCE_NOT_PASS")
    return errors


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--report", type=Path, default=DEFAULT_REPORT, help="Path to deployed application audit JSON")
    args = parser.parse_args()
    try:
        report = json.loads(args.report.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        print(f"LIVE_BRIDGE_AUDIT_ACCEPTANCE=FAIL\nREPORT_READ_ERROR={exc}")
        return 2
    if not isinstance(report, dict):
        print("LIVE_BRIDGE_AUDIT_ACCEPTANCE=FAIL\nREPORT_ROOT_NOT_OBJECT")
        return 2
    errors = validate_report(report)
    if errors:
        print("LIVE_BRIDGE_AUDIT_ACCEPTANCE=FAIL")
        for error in errors:
            print(f"BLOCKER={error}")
        return 1
    print("LIVE_BRIDGE_AUDIT_ACCEPTANCE=PASS")
    print(f"SOURCE={args.report}")
    selected_ids = report.get("target_request_ids", [])
    print(f"REQUEST_A={selected_ids[0]}")
    print(f"REQUEST_B={selected_ids[1]}")
    print("CANONICAL_MESSAGE_REQUEST_ROUND=2/2/2")
    print("PERSISTED_RUNTIME_EXECUTION_EVENTS=4")
    print("STRICT_LIVE_BRIDGE_EVIDENCE=2 PASS / 2 distinct bridge hashes")
    print("SIDE_EFFECTS=NONE_OBSERVED")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
